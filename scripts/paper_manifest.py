"""Check, record and compare the figures that the paper includes.

  check    every \\includegraphics path in the manuscript exists in --figures
           (static assets listed in STATIC_FIGURES are taken from the paper),
  manifest write MANIFEST.json (git state, lock-file hash, sha256 per figure),
  compare  compare --figures against --reference: PNGs pixel by pixel,
           PDFs by rasterising both pages with pdftoppm at 100 dpi.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

import matplotlib.image as mpimg
import numpy as np

PROJECT_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_TEX = PROJECT_ROOT.parent / "motivation-for-springer" / "sn-article.tex"
# Not generated by code: a photo and an illustration supplied with the paper.
STATIC_FIGURES = {"figures/homogeinity.png", "figures/exp_still.png"}
INCLUDE_RE = re.compile(r"^[^%\n]*\\includegraphics(?:\[[^\]]*\])?\{([^}]+)\}", re.MULTILINE)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("action", choices=["check", "manifest", "compare"])
    parser.add_argument("--tex", type=Path, default=DEFAULT_TEX)
    parser.add_argument("--figures", type=Path, required=True, help="Generated figures dir.")
    parser.add_argument("--reference", type=Path, help="Reference figures dir (compare).")
    return parser.parse_args()


def included_figures(tex: Path) -> list[str]:
    return [m.group(1) for m in INCLUDE_RE.finditer(tex.read_text(encoding="utf-8"))]


def generated_names(tex: Path) -> list[str]:
    return [Path(p).name for p in included_figures(tex) if p not in STATIC_FIGURES]


def check(args: argparse.Namespace) -> int:
    missing = [n for n in generated_names(args.tex) if not (args.figures / n).exists()]
    for name in missing:
        print(f"MISSING {name}")
    print(f"{len(generated_names(args.tex)) - len(missing)} generated figures present, "
          f"{len(missing)} missing, {len(STATIC_FIGURES)} static")
    return 1 if missing else 0


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def git(*cmd: str) -> str:
    return subprocess.run(["git", *cmd], cwd=PROJECT_ROOT, capture_output=True,
                          text=True, check=True).stdout.strip()


def manifest(args: argparse.Namespace) -> int:
    data = {
        "git_commit": git("rev-parse", "HEAD"),
        "git_dirty_tracked": bool(git("status", "--porcelain", "--untracked-files=no")),
        "python": sys.version.split()[0],
        "requirements_lock_sha256": sha256(PROJECT_ROOT / "requirements-lock.txt"),
        "figures": {n: sha256(args.figures / n) for n in generated_names(args.tex)
                    if (args.figures / n).exists()},
    }
    out = args.figures / "MANIFEST.json"
    out.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {out}")
    return 0


def raster(path: Path, workdir: Path) -> list[np.ndarray]:
    if path.suffix.lower() != ".pdf":
        return [mpimg.imread(path)[..., :3]]
    prefix = workdir / path.stem
    subprocess.run(["pdftoppm", "-r", "100", "-png", str(path), str(prefix)], check=True)
    return [mpimg.imread(p)[..., :3] for p in sorted(workdir.glob(path.stem + "-*.png"))]


def compare_one(generated: Path, reference: Path, workdir: Path) -> str:
    if not reference.exists():
        return "NO-REFERENCE"
    if generated.read_bytes() == reference.read_bytes():
        return "IDENTICAL"
    a = raster(generated, workdir / "a")
    b = raster(reference, workdir / "b")
    if len(a) != len(b) or any(x.shape != y.shape for x, y in zip(a, b)):
        return "DIFFERENT-SIZE"
    diff = max(int((np.abs(x - y).max(axis=2) > 0).sum()) for x, y in zip(a, b))
    return "PIXEL-IDENTICAL" if diff == 0 else f"DIFFERS ({diff} px)"


def compare(args: argparse.Namespace) -> int:
    if args.reference is None:
        raise SystemExit("compare needs --reference")
    failures = 0
    with tempfile.TemporaryDirectory() as tmp:
        for name in generated_names(args.tex):
            work = Path(tmp) / name
            (work / "a").mkdir(parents=True)
            (work / "b").mkdir(parents=True)
            status = compare_one(args.figures / name, args.reference / name, work)
            failures += status not in ("IDENTICAL", "PIXEL-IDENTICAL")
            print(f"{status:20s} {name}")
    print(f"{failures} figure(s) not identical")
    return 1 if failures else 0


def main() -> int:
    args = parse_args()
    return {"check": check, "manifest": manifest, "compare": compare}[args.action](args)


if __name__ == "__main__":
    sys.exit(main())
